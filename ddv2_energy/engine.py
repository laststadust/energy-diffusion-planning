"""Frozen training-time energy evaluator.

Road energy uses whole-vehicle signed-distance samples. Interaction energy
uses the contour and vehicle-safety graphs. The evaluator is not registered
as a policy module and does not modify inference trajectories.
"""
from pathlib import Path
import re
import torch

from .geometry import road_energy
from .interaction import InteractionConfig, InteractionEnergy
from .trajectory import pose_traj
from .contexts import ContextStore, current_only


class FrozenEnergyEngine:
    def __init__(self, config, device, *, allow_test_checkpoint=False):
        if not config.enabled:
            raise ValueError("Do not instantiate energy scoring in original/zero-strength mode")
        self.config = config
        self.device = torch.device(device)
        self.store = ContextStore(config.context_root)
        path = Path(config.graph_checkpoint)
        if not path.is_file():
            raise FileNotFoundError("A separately supervised V2 dual-graph checkpoint is required: " + str(path))
        # Only load files generated by our own trusted graph_fit.py. Pickle is not
        # an interchange format for weights downloaded from untrusted sources.
        checkpoint = torch.load(path, map_location="cpu", weights_only=False)
        provenance = checkpoint.get("provenance", {})
        if provenance.get("synthetic", False) and not allow_test_checkpoint:
            raise ValueError("Synthetic smoke-test graph weights are not experimental weights")
        if (checkpoint.get("format") != "ddv2_dual_graph_v1"
                or checkpoint.get("trained_steps", 0) <= 0
                or provenance.get("source") != "DiffusionDriveV2"
                or not re.fullmatch(r"[0-9a-f]{64}", provenance.get("checkpoint_sha256", ""))):
            raise ValueError("Graph checkpoint lacks supervised V2 candidate provenance")
        train_logs, val_logs = set(provenance.get("train_logs", [])), set(provenance.get("val_logs", []))
        if not train_logs or not val_logs or train_logs & val_logs:
            raise ValueError("Graph checkpoint must have disjoint training/validation logs")
        self.graph_config = InteractionConfig(**checkpoint["config"])
        self.provenance = provenance
        # Constructing the frozen reward network must not consume the policy RNG.
        with torch.random.fork_rng(devices=[]):
            self.graph = InteractionEnergy(self.graph_config)
        self.graph.load_state_dict(checkpoint["state_dict"], strict=True)
        self.graph.to(device=self.device, dtype=torch.float32).eval().requires_grad_(False)
        if not all(bool(torch.isfinite(p).all()) for p in self.graph.parameters()):
            raise ValueError("Nonfinite graph weights")

    @torch.no_grad()
    def score(self, poses, tokens):
        """Score unchanged rear-axle poses [B,K,8,3] at 0.5 s; costs [B,K]."""
        if (poses.ndim != 4 or poses.shape[-2:] != (8, 3) or poses.shape[1] < 1
                or not torch.is_floating_point(poses) or not bool(torch.isfinite(poses).all())):
            raise ValueError("Expected finite NAVSIM [B,K,8,3] poses")
        if isinstance(tokens, str) or tokens is None or len(tokens) != poses.shape[0]:
            raise ValueError("One scene token per batch item is required")
        if poses.device != self.device:
            raise ValueError("Reward engine device differs from policy device")
        road, interaction = [], []
        # Stable full-precision geometry even when the policy uses mixed precision.
        with torch.autocast(device_type=self.device.type, enabled=False):
            for b, token in enumerate(tokens):
                ctx = current_only(self.store.load(token))
                if ctx["split"] != "train":
                    raise ValueError("RL energy scoring requires training contexts, not val/navtest")
                if ctx["truncated"]:
                    raise ValueError("Reward actor set was truncated; rebuild with a larger actor cap")
                rc, ic = [], []
                for block in poses[b].detach().float().split(self.config.chunk_size):
                    count = len(block)
                    traj = pose_traj(block, ctx["v0"], dt=.5)
                    actors = torch.as_tensor(ctx["actors"], device=self.device, dtype=torch.float32)[None].expand(count, -1, -1)
                    mask = torch.as_tensor(ctx["mask"], device=self.device, dtype=torch.bool)[None].expand(count, -1)
                    sdf = torch.as_tensor(ctx["sdf"], device=self.device, dtype=torch.float32)[None]
                    cfg = self.graph_config
                    rc.append(road_energy(traj, sdf, ctx["origin"], ctx["resolution"],
                                          length=cfg.ego_length, width=cfg.ego_width,
                                          rear_axle_to_center=cfg.rear_axle_to_center))
                    ic.append(self.graph(traj, actors, mask, dt=.5))
                road.append(torch.cat(rc)); interaction.append(torch.cat(ic))
        road, interaction = torch.stack(road), torch.stack(interaction)
        for cost in (road, interaction):
            if cost.shape != poses.shape[:2] or not bool(torch.isfinite(cost).all()) or bool((cost < 0).any()):
                raise ValueError("Reward engine returned invalid energy; do not silently use zero risk")
        return road.detach(), interaction.detach()


def apply_energy_reward(head, poses, tokens, pdm, original, subscores):
    """Optional bridge invoked after original PDM scoring, before step discount."""
    from .config import EnergyRLConfig
    from .rewards import energy_advantages
    config = EnergyRLConfig.from_agent_config(head._config)
    if not config.enabled:
        return original, {}
    engine = getattr(head, "_energy_reward_engine", None)
    if engine is None or engine.config != config or engine.device != poses.device:
        engine = FrozenEnergyEngine(config, poses.device)
        # A plain helper, NOT nn.Module: no new policy checkpoint keys/optimizer params.
        head._energy_reward_engine = engine
    road, interaction = engine.score(poses, tokens)
    unsafe = torch.zeros_like(pdm, dtype=torch.bool)
    for name in ("no_collision", "drivable_area"):
        if name not in subscores:
            raise ValueError("Missing safety subscore: " + name)
        unsafe |= subscores[name][:, :-1].reshape_as(pdm) != 1
    return energy_advantages(pdm, original, road.reshape_as(pdm),
                             interaction.reshape_as(pdm), unsafe, config)
